export function getWidgetLang(langProp?: SupportedLang): SupportedLang {
  if (langProp && widgetTranslations[langProp]) return langProp;
  if (typeof window !== 'undefined') {
    const path = window.location.pathname;
    const match = path.match(/^\/([a-z]{2}(-[a-z]{2})?)/i);
    if (match && widgetTranslations[match[1].toLowerCase() as SupportedLang]) {
      return match[1].toLowerCase() as SupportedLang;
    }
  }
  return 'en';
}
